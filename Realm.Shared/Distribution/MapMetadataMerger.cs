using System.Text;
using System.Text.Encodings.Web;
using System.Text.Json;
using System.Text.Json.Nodes;
using Realm.Shared.Metadata;
using Realm.Shared.Services;

namespace Realm.Shared.Distribution;

public sealed record MapMetadataDocument(string ContributorName, byte[] Content);

public readonly record struct MapMetadataMergeResult(
	bool Success,
	string ErrorMessage,
	byte[] MergedBytes,
	byte[] ParentIntentBytes,
	IReadOnlyList<string> OverriddenKeys)
{
	public static MapMetadataMergeResult Failure(string errorMessage)
	{
		return new MapMetadataMergeResult(false, errorMessage, Array.Empty<byte>(), Array.Empty<byte>(), Array.Empty<string>());
	}
}

/// <summary>
///     Merges the <c>metadata.json</c> of a map and of every map it references into the one document the parent keeps.
/// </summary>
/// <remarks>
///     The merge is unconditional and has no conflict mode: a referenced map's keys are laid down first, alphabetically by
///     map name, and the parent's own values are laid down last, so the parent takes precedence wherever both state a
///     value. Objects merge key by key, arrays are combined with each entry kept once by the slug that identifies it, and a
///     scalar or an array entry both maps state differently carries the last contributor's value.
///     <para />
///     A null is not a value: the canonical schema writes every property into a map's metadata and leaves the ones the
///     author did not set null, so a parent that states null is stating nothing, and a referenced map's value for that key
///     survives. Only a parent value that is actually set overrides what a referenced map states.
///     <para />
///     The parent's metadata file on disk is already the merged result of the previous save, so it cannot be merged as if
///     it were the parent's own content: every key a referenced map also states would look like an intentional override.
///     What the parent intended is therefore recovered by diffing the parent's file against the merge of the referenced
///     maps, and that difference - and only that difference - is what the merge applies last. It is what
///     <c>metadata.partial.json</c> holds, so a referenced map can be replaced with a newer version and the parent keeps
///     exactly the overrides a person stated rather than the whole of the last merged document.
///     <para />
///     The referenced maps' document is first put into the schema's canonical shape, the shape the editor writes a metadata
///     file in: every property present, the ones the author left unset stated as null or as their default. A map authored by
///     hand or generated by a script states only what its author wrote, so compared as written its <c>CritMultiplier</c>
///     would be absent while the editor's copy of the same unit states <c>1</c>, and every default would read as a parent
///     override. The parent is merged exactly as it states its values, because those values are the ones the document is
///     written with, keys the schema does not model included.
/// </remarks>
public static class MapMetadataMerger
{
	public const string MetadataFileName = "metadata.json";

	public const string MetadataPartialFileName = "metadata.partial.json";

	private const string TemplateContainerKey = "Templates";

	private static readonly string[] SlugKeys = { "TemplateID", "Id", "ID", "Key" };

	private static readonly JsonDocumentOptions ParseOptions = new()
	{
		AllowTrailingCommas = true,
		CommentHandling = JsonCommentHandling.Skip
	};

	private static readonly JsonSerializerOptions SerializationOptions = new()
	{
		WriteIndented = true,
		Encoder = JavaScriptEncoder.UnsafeRelaxedJsonEscaping
	};

	/// <summary>
	///     Merges the referenced maps' metadata into the parent's.
	/// </summary>
	/// <param name="referencedMetadata">The referenced maps' metadata, already in the order they merge in.</param>
	/// <param name="parentMetadata">The parent's own metadata file as it currently sits on disk.</param>
	/// <returns>The merged document, the parent's own overrides, and the keys the parent overrode.</returns>
	public static MapMetadataMergeResult Merge(IReadOnlyList<MapMetadataDocument> referencedMetadata, byte[] parentMetadata)
	{
		if (!TryParse(referencedMetadata, parentMetadata, out JsonObject referencedOnly, out JsonObject parentObject, out string errorMessage))
		{
			return MapMetadataMergeResult.Failure(errorMessage);
		}

		var overriddenKeys = new List<string>();
		JsonObject parentIntent = ComputeParentIntent(referencedOnly, parentObject, string.Empty, overriddenKeys);

		var merged = (JsonObject)referencedOnly.DeepClone();
		MergeInto(merged, parentIntent);

		return new MapMetadataMergeResult(
			true,
			string.Empty,
			Serialize(merged),
			Serialize(parentIntent),
			overriddenKeys);
	}

	/// <summary>
	///     Answers whether the parent's overrides still produce the same document when they are laid over the referenced
	///     maps a second time, which is what a save relies on being true.
	/// </summary>
	/// <param name="referencedMetadata">The referenced maps' metadata, in merge order.</param>
	/// <param name="parentIntent">The overrides the first pass recovered.</param>
	/// <param name="expectedMerged">The document the first pass produced.</param>
	/// <param name="errorMessage">The key that did not settle, when the merge is not idempotent.</param>
	/// <returns>True when merging twice produces the same document.</returns>
	public static bool VerifyIdempotent(
		IReadOnlyList<MapMetadataDocument> referencedMetadata,
		byte[] parentIntent,
		byte[] expectedMerged,
		out string errorMessage)
	{
		errorMessage = string.Empty;

		if (!TryParse(referencedMetadata, parentIntent, out JsonObject referencedOnly, out JsonObject intentObject, out string parseError))
		{
			errorMessage = parseError;
			return false;
		}

		var merged = (JsonObject)referencedOnly.DeepClone();
		MergeInto(merged, intentObject);

		JsonObject expected;
		try
		{
			expected = JsonNode.Parse(Encoding.UTF8.GetString(expectedMerged).TrimStart('\uFEFF'), documentOptions: ParseOptions) as JsonObject;
		}
		catch (Exception exception) when (exception is JsonException or ArgumentException)
		{
			errorMessage = $"The merged {MetadataFileName} could not be read back: {exception.Message}";
			return false;
		}

		if (expected == null || !JsonNode.DeepEquals(merged, expected))
		{
			errorMessage = $"Merging {MetadataFileName} is not stable: taking the referenced maps on their own and applying {MetadataPartialFileName} " +
			               "does not reproduce the document the save just wrote, so a key is being read from the parent that no override records.";
			return false;
		}

		return true;
	}

	private static bool TryParse(
		IReadOnlyList<MapMetadataDocument> referencedMetadata,
		byte[] secondDocument,
		out JsonObject referencedOnly,
		out JsonObject parentObject,
		out string errorMessage)
	{
		referencedOnly = new JsonObject();
		parentObject = new JsonObject();
		errorMessage = string.Empty;

		if (referencedMetadata != null)
		{
			foreach (MapMetadataDocument document in referencedMetadata)
			{
				if (document == null || document.Content == null || document.Content.Length == 0)
				{
					continue;
				}

				JsonObject? parsed = ParseObject(document.Content, document.ContributorName, out errorMessage);
				if (parsed == null)
				{
					return false;
				}

				MergeInto(referencedOnly, parsed);
			}

			referencedOnly = ToSchemaShape(referencedOnly);
		}

		if (secondDocument == null || secondDocument.Length == 0)
		{
			return true;
		}

		JsonObject? parsedSecond = ParseObject(secondDocument, "the parent map", out errorMessage);
		if (parsedSecond == null)
		{
			return false;
		}

		parentObject = parsedSecond;
		return true;
	}

	private static JsonObject? ParseObject(byte[] content, string contributorName, out string errorMessage)
	{
		errorMessage = string.Empty;
		ReadOnlyMemory<byte> payload = content;
		if (payload.Length >= 3 && payload.Span[0] == 0xEF && payload.Span[1] == 0xBB && payload.Span[2] == 0xBF)
		{
			payload = payload.Slice(3);
		}

		try
		{
			if (JsonNode.Parse(payload.Span, documentOptions: ParseOptions) is JsonObject parsed)
			{
				return parsed;
			}
		}
		catch (Exception exception) when (exception is JsonException or ArgumentException)
		{
			errorMessage = $"The {MetadataFileName} of {contributorName} is not valid JSON: {exception.Message}";
			return null;
		}

		errorMessage = $"The {MetadataFileName} of {contributorName} must contain a JSON object at the top level.";
		return null;
	}

	/// <summary>
	///     Puts a metadata document into the shape the editor writes one in, so a map that states only what its author wrote
	///     and a map that states every property at its default compare equal where they describe the same thing.
	/// </summary>
	private static JsonObject ToSchemaShape(JsonObject document)
	{
		if (document.Count == 0)
		{
			return document;
		}

		try
		{
			MapMetadata typed = MapFileService.LoadMetadataFromJson(document.ToJsonString(SerializationOptions));
			if (JsonNode.Parse(MapFileService.SaveMetadataToJson(typed), documentOptions: ParseOptions) is JsonObject canonical &&
			    canonical.Count > 0 &&
			    KeepsEveryTemplate(canonical, document))
			{
				return canonical;
			}
		}
		catch (Exception exception) when (exception is JsonException or ArgumentException or NotSupportedException)
		{
		}

		return document;
	}

	/// <summary>
	///     Answers whether the schema read of a document kept every template the document states, so a file the schema cannot
	///     represent is merged as written rather than through a shape that dropped part of it.
	/// </summary>
	private static bool KeepsEveryTemplate(JsonObject canonical, JsonObject original)
	{
		if (original[TemplateContainerKey] is not JsonObject originalTemplates)
		{
			return true;
		}

		if (canonical[TemplateContainerKey] is not JsonObject canonicalTemplates)
		{
			return originalTemplates.Count == 0;
		}

		foreach (KeyValuePair<string, JsonNode?> category in originalTemplates)
		{
			if (category.Value is not JsonArray originalEntries)
			{
				continue;
			}

			var canonicalIdentifiers = new HashSet<string>(StringComparer.Ordinal);
			if (canonicalTemplates[category.Key] is JsonArray canonicalEntries)
			{
				foreach (JsonNode? entry in canonicalEntries)
				{
					string identifier = TryGetSlug(entry);
					if (!string.IsNullOrEmpty(identifier)) canonicalIdentifiers.Add(identifier);
				}
			}

			foreach (JsonNode? entry in originalEntries)
			{
				string identifier = TryGetSlug(entry);
				if (!string.IsNullOrEmpty(identifier) && !canonicalIdentifiers.Contains(identifier))
				{
					return false;
				}
			}
		}

		return true;
	}

	private static void MergeInto(JsonObject target, JsonObject source, bool replaceArrays = false)
	{
		foreach (KeyValuePair<string, JsonNode?> property in source)
		{
			if (!target.TryGetPropertyValue(property.Key, out JsonNode? existing))
			{
				target[property.Key] = property.Value?.DeepClone();
				continue;
			}

			if (existing is JsonObject existingObject && property.Value is JsonObject incomingObject)
			{
				MergeInto(existingObject, incomingObject, replaceArrays);
				continue;
			}

			if (existing is JsonArray existingArray && property.Value is JsonArray incomingArray)
			{
				MergeArray(existingArray, incomingArray, replaceArrays);
				continue;
			}

			target[property.Key] = property.Value?.DeepClone();
		}
	}

	/// <summary>
	///     Lays one array over another. An entry with a slug is merged into the entry of the same slug field by field,
	///     which is what lets a parent state one property of a referenced template without freezing every other property
	///     at the version it was read from. An array a template's own field states is replaced whole, because a list inside
	///     a template is that template's value rather than a set the parent extends.
	/// </summary>
	private static void MergeArray(JsonArray target, JsonArray source, bool replaceArrays = false)
	{
		if (replaceArrays && !HasSluggedEntry(source))
		{
			target.Clear();
			foreach (JsonNode? entry in source)
			{
				target.Add(entry?.DeepClone());
			}

			return;
		}

		foreach (JsonNode? entry in source)
		{
			string slug = TryGetSlug(entry);
			if (!string.IsNullOrEmpty(slug))
			{
				JsonNode? merged = entry?.DeepClone();
				for (int index = target.Count - 1; index >= 0; index--)
				{
					if (!string.Equals(TryGetSlug(target[index]), slug, StringComparison.Ordinal)) continue;

					if (target[index] is JsonObject existingObject && merged is JsonObject incomingObject)
					{
						var combined = (JsonObject)existingObject.DeepClone();
						MergeInto(combined, incomingObject, replaceArrays: true);
						merged = combined;
					}

					target.RemoveAt(index);
				}

				target.Add(merged);
				continue;
			}

			if (!ContainsDeepEqual(target, entry))
			{
				target.Add(entry?.DeepClone());
			}
		}
	}

	private static bool HasSluggedEntry(JsonArray array)
	{
		foreach (JsonNode? entry in array)
		{
			if (!string.IsNullOrEmpty(TryGetSlug(entry))) return true;
		}

		return false;
	}

	/// <summary>
	///     Recovers the parent's own values: every key it states that the referenced maps do not already produce.
	/// </summary>
	private static JsonObject ComputeParentIntent(JsonObject referenced, JsonObject parent, string pathPrefix, List<string> overriddenKeys)
	{
		var intent = new JsonObject();

		foreach (KeyValuePair<string, JsonNode?> property in parent)
		{
			string displayPath = string.IsNullOrEmpty(pathPrefix) ? property.Key : $"{pathPrefix}.{property.Key}";

			if (!referenced.TryGetPropertyValue(property.Key, out JsonNode? existing))
			{
				intent[property.Key] = property.Value?.DeepClone();
				continue;
			}

			if (existing is JsonObject existingObject && property.Value is JsonObject parentObject)
			{
				JsonObject nested = ComputeParentIntent(existingObject, parentObject, displayPath, overriddenKeys);
				if (nested.Count > 0)
				{
					intent[property.Key] = nested;
				}

				continue;
			}

			if (existing is JsonArray existingArray && property.Value is JsonArray parentArray)
			{
				if (HasSluggedEntry(parentArray) || HasSluggedEntry(existingArray))
				{
					JsonArray additions = ComputeArrayIntent(existingArray, parentArray, displayPath, overriddenKeys);
					if (additions.Count > 0)
					{
						intent[property.Key] = additions;
					}
				}
				else if (!JsonNode.DeepEquals(existingArray, parentArray))
				{
					intent[property.Key] = parentArray.DeepClone();
					overriddenKeys.Add(displayPath);
				}

				continue;
			}

			if (JsonNode.DeepEquals(existing, property.Value))
			{
				continue;
			}

			if (existing != null && property.Value == null)
			{
				continue;
			}

			intent[property.Key] = property.Value?.DeepClone();
			overriddenKeys.Add(displayPath);
		}

		return intent;
	}

	private static JsonArray ComputeArrayIntent(JsonArray referenced, JsonArray parent, string displayPath, List<string> overriddenKeys)
	{
		var intent = new JsonArray();

		foreach (JsonNode? entry in parent)
		{
			string slug = TryGetSlug(entry);
			if (!string.IsNullOrEmpty(slug))
			{
				JsonNode? existing = null;
				foreach (JsonNode? candidate in referenced)
				{
					if (string.Equals(TryGetSlug(candidate), slug, StringComparison.Ordinal))
					{
						existing = candidate;
						break;
					}
				}

				if (existing is JsonObject existingObject && entry is JsonObject parentEntry)
				{
					JsonObject nested = ComputeParentIntent(existingObject, parentEntry, $"{displayPath}[{slug}]", overriddenKeys);
					if (nested.Count == 0) continue;

					var intentEntry = new JsonObject { [SlugKeyOf(parentEntry)] = slug };
					MergeInto(intentEntry, nested, replaceArrays: true);
					intent.Add(intentEntry);
					continue;
				}

				if (existing != null && JsonNode.DeepEquals(existing, entry))
				{
					continue;
				}

				intent.Add(entry?.DeepClone());
				overriddenKeys.Add($"{displayPath}[{slug}]");
				continue;
			}

			if (ContainsDeepEqual(referenced, entry))
			{
				continue;
			}

			intent.Add(entry?.DeepClone());
			overriddenKeys.Add($"{displayPath}[]");
		}

		return intent;
	}

	private static string SlugKeyOf(JsonObject entry)
	{
		foreach (string slugKey in SlugKeys)
		{
			if (entry[slugKey] is JsonValue value && value.TryGetValue(out string text) && !string.IsNullOrWhiteSpace(text)) return slugKey;
		}

		return SlugKeys[0];
	}

	private static string TryGetSlug(JsonNode? entry)
	{
		if (entry is not JsonObject entryObject)
		{
			return string.Empty;
		}

		foreach (string slugKey in SlugKeys)
		{
			if (entryObject[slugKey] is JsonValue value && value.TryGetValue(out string text) && !string.IsNullOrWhiteSpace(text))
			{
				return text;
			}
		}

		return string.Empty;
	}

	private static bool ContainsDeepEqual(JsonArray array, JsonNode? candidate)
	{
		foreach (JsonNode? entry in array)
		{
			if (JsonNode.DeepEquals(entry, candidate))
			{
				return true;
			}
		}

		return false;
	}

	private static byte[] Serialize(JsonObject document)
	{
		return Encoding.UTF8.GetBytes(document.ToJsonString(SerializationOptions));
	}
}

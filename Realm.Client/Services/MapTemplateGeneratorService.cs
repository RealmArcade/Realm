using System;
using System.Collections.Generic;
using System.IO;
using System.Linq;
using System.Text;
using System.Text.RegularExpressions;
using Realm.Client.Utils;
using Realm.Shared.Metadata;

namespace Realm.Client.Services;

public static partial class MapTemplateGeneratorService
{
	[GeneratedRegex(@"[^a-zA-Z0-9]+")]
	private static partial Regex WordSplitRegex();

	public static string SanitizeIdentifier(string input)
	{
		if (string.IsNullOrWhiteSpace(input)) return "Template";

		string slug = input.Trim();
		int slashIdx = slug.LastIndexOf('/');
		if (slashIdx >= 0)
		{
			slug = slug.Substring(slashIdx + 1);
		}

		if (string.IsNullOrWhiteSpace(slug)) return "Template";

		string[] parts = WordSplitRegex().Split(slug);
		var sb = new StringBuilder();
		foreach (var part in parts)
		{
			if (string.IsNullOrEmpty(part)) continue;
			sb.Append(char.ToUpperInvariant(part[0]));
			if (part.Length > 1)
			{
				sb.Append(part.Substring(1));
			}
		}

		string ident = sb.ToString();
		if (string.IsNullOrEmpty(ident))
		{
			ident = "Template";
		}

		if (char.IsDigit(ident[0]))
		{
			ident = "_" + ident;
		}

		return ident;
	}

	public static string GenerateMapTemplatesCode(MapMetadata metadata)
	{
		var sb = new StringBuilder();
		sb.AppendLine("// <auto-generated>");
		sb.AppendLine("// This code was generated by Realm MapTemplate Generator.");
		sb.AppendLine("// Changes to this file may cause incorrect behavior and will be lost if the code is regenerated.");
		sb.AppendLine("// </auto-generated>");
		sb.AppendLine();
		sb.AppendLine("#nullable enable");
		sb.AppendLine();
		sb.AppendLine("namespace Realm.Maps;");
		sb.AppendLine();

		void EmitClass(string className, IEnumerable<string>? items)
		{
			sb.AppendLine($"public static class {className}");
			sb.AppendLine("{");

			if (items != null)
			{
				var usedIdents = new HashSet<string>(StringComparer.Ordinal);
				foreach (var rawValue in items)
				{
					if (string.IsNullOrWhiteSpace(rawValue)) continue;

					string baseIdent = SanitizeIdentifier(rawValue);
					string ident = baseIdent;
					int suffix = 2;
					while (!usedIdents.Add(ident))
					{
						ident = $"{baseIdent}_{suffix++}";
					}

					sb.AppendLine($"\tpublic const string {ident} = \"{rawValue}\";");
				}
			}

			sb.AppendLine("}");
			sb.AppendLine();
		}

		var templates = metadata?.Templates;

		EmitClass("UnitIds", templates?.Units?.Select(u => u.TemplateID));
		EmitClass("BuildingIds", templates?.Buildings?.Select(b => b.TemplateID));
		EmitClass("ResourceIds", templates?.Resources?.Select(r => r.TemplateID));
		EmitClass("PropIds", templates?.Props?.Select(p => p.TemplateID));
		EmitClass("AbilityIds", templates?.Abilities?.Select(a => a.TemplateID));
		EmitClass("WeaponIds", templates?.Weapons?.Select(w => w.TemplateID));
		EmitClass("UpgradeIds", templates?.Upgrades?.Select(u => u.TemplateID));
		EmitClass("ItemIds", templates?.Items?.Select(i => i.TemplateID));
		EmitClass("VfxIds", templates?.Vfx?.Select(v => v.VfxId));
		EmitClass("WaterProfileIds", metadata?.CustomWaterProfiles?.Select(w => w.Id));

		return sb.ToString();
	}

	public static void EnsureMapTemplates(string workspacePath, MapMetadata? metadata = null)
	{
		if (string.IsNullOrWhiteSpace(workspacePath)) return;

		if (!Directory.Exists(workspacePath)) return;

		string metadataPath = MetadataService.ResolveMetadataPath(workspacePath);
		if (metadata == null && File.Exists(metadataPath))
		{
			try
			{
				metadata = Realm.Shared.Services.MapFileService.LoadMetadata(metadataPath);
			}
			catch
			{
			}
		}

		metadata ??= new MapMetadata();

		string generatedCode = GenerateMapTemplatesCode(metadata);
		string targetFilePath = Path.Combine(workspacePath, "MapTemplates.g.cs");

		try
		{
			if (File.Exists(targetFilePath))
			{
				string existingCode = File.ReadAllText(targetFilePath);
				if (string.Equals(existingCode, generatedCode, StringComparison.Ordinal))
				{
					return;
				}
			}

			File.WriteAllText(targetFilePath, generatedCode);
		}
		catch (Exception ex)
		{
			Godot.GD.PrintErr($"[MapTemplateGeneratorService] Failed to write MapTemplates.g.cs to {targetFilePath}: {ex.Message}");
		}
	}

	public static void EnsureWasmEntryPoint(string workspacePath)
	{
		if (string.IsNullOrWhiteSpace(workspacePath) || !Directory.Exists(workspacePath)) return;

		string legacyEntryPointPath = Path.Combine(workspacePath, "WasmEntryPoint.cs");
		if (File.Exists(legacyEntryPointPath))
		{
			try
			{
				var legacyAttributes = File.GetAttributes(legacyEntryPointPath);
				if ((legacyAttributes & FileAttributes.ReadOnly) != 0)
				{
					File.SetAttributes(legacyEntryPointPath, legacyAttributes & ~FileAttributes.ReadOnly);
				}
				File.Delete(legacyEntryPointPath);
			}
			catch (Exception exception)
			{
				Godot.GD.PrintErr($"[MapTemplateGeneratorService] Failed to delete legacy WasmEntryPoint.cs in {workspacePath}: {exception.Message}");
			}
		}

		string templatePath = PathUtils.FindPath("MapTemplate/WasmEntryPoint.g.cs");
		if (string.IsNullOrEmpty(templatePath) || !File.Exists(templatePath)) return;

		string targetFilePath = Path.Combine(workspacePath, "WasmEntryPoint.g.cs");

		try
		{
			string templateCode = File.ReadAllText(templatePath);
			if (File.Exists(targetFilePath))
			{
				string existingCode = File.ReadAllText(targetFilePath);
				if (string.Equals(existingCode.Replace("\r\n", "\n"), templateCode.Replace("\r\n", "\n"), StringComparison.Ordinal))
				{
					return;
				}

				var attributes = File.GetAttributes(targetFilePath);
				if ((attributes & FileAttributes.ReadOnly) != 0)
				{
					File.SetAttributes(targetFilePath, attributes & ~FileAttributes.ReadOnly);
				}
			}

			File.WriteAllText(targetFilePath, templateCode);
		}
		catch (Exception exception)
		{
			Godot.GD.PrintErr($"[MapTemplateGeneratorService] Failed to write WasmEntryPoint.g.cs to {targetFilePath}: {exception.Message}");
		}
	}
}
